import { BadRequestException, HttpException, HttpStatus, Injectable, Logger, NotFoundException, OnModuleInit } from "@nestjs/common";
import type { GarmentAsset3d } from "@prisma/client";
import { AiClient } from "../../common/ai.client";
import { aiSpend } from "../../common/metrics";
import { MeteringService } from "../../common/metering.service";
import { PrismaService } from "../../common/prisma.service";
import { StorageService } from "../../common/storage.service";
import { GenerationService } from "../looks/generation.service";
import { allowanceAllows, ASSET_3D, checkAssetBudget, pickModelSize } from "./xr-rules";

export const ASSET_3D_JOB = "asset3d";
export const AI_3D_LABEL = "3D preview generated by AI";

interface Garment3dResult {
  glb_b64: string;
  poster_b64: string;
  triangles: number;
  vertices: number;
  bytes: number;
  dimensions_m: { width: number; height: number; depth: number };
  model_version: string;
  sha256: string;
}

/**
 * E27 image-to-3D garment pipeline (FR-3D-01a/02/03/06/07, FR-CAT-10).
 * Requested from the studio, generated on the shared BullMQ generation queue (job "asset3d"),
 * stored as member-owned public media per variant, metered as ASSET_3D against the page allowance,
 * and shown to shoppers only after the page approves it.
 */
@Injectable()
export class Asset3dService implements OnModuleInit {
  private log = new Logger("Asset3d");

  constructor(
    private prisma: PrismaService,
    private storage: StorageService,
    private ai: AiClient,
    private metering: MeteringService,
    private generations: GenerationService,
  ) {}

  onModuleInit() {
    this.generations.handle(ASSET_3D_JOB, (job) => this.process(job.data.id as string));
  }

  async allowance(pageId: string) {
    const page = await this.prisma.page.findUnique({ where: { id: pageId }, include: { subscription: true } });
    const sub = page?.subscription ?? null;
    const used = sub
      ? await this.prisma.usageEvent.count({ where: { pageId, source: "PAGE_ALLOWANCE", createdAt: { gte: sub.periodStart } } })
      : 0;
    return { cap: sub?.monthlyCap ?? null, used };
  }

  /** Queue 3D generation for a product's colours (all with a cut-out, or the ones asked for). */
  async request(productId: string, userId: string, variantIds?: string[]) {
    const product = await this.prisma.product.findUnique({ where: { id: productId }, include: { variants: true } });
    if (!product) throw new NotFoundException("Product not found");
    const targets = product.variants.filter((v) => v.cutoutPath && (!variantIds?.length || variantIds.includes(v.id)));
    if (!targets.length) throw new BadRequestException("Add a photo for a colour first: the 3D model is built from its try-on cut-out.");
    await this.metering.assertBudgetOpen();
    const { cap, used } = await this.allowance(product.pageId);
    if (!allowanceAllows(cap, used, targets.length)) {
      throw new HttpException(
        { message: `Your page allowance has ${Math.max(0, (cap ?? 0) - used)} AI actions left this month; 3D needs ${targets.length}.`, code: "ALLOWANCE" },
        HttpStatus.PAYMENT_REQUIRED,
      );
    }
    for (const v of targets) {
      const existing = await this.prisma.garmentAsset3d.findUnique({ where: { variantId: v.id } });
      if (existing && (existing.status === "QUEUED" || existing.status === "GENERATING")) continue;
      const data = {
        productId,
        pageId: product.pageId,
        status: "QUEUED",
        progress: 0,
        approved: false, // a regenerated model needs a fresh review (FR-3D-06)
        error: null,
        size: pickModelSize(v.sizes),
        requestedBy: userId,
      };
      const row = await this.prisma.garmentAsset3d.upsert({ where: { variantId: v.id }, create: { variantId: v.id, ...data }, update: data });
      await this.generations.enqueue(ASSET_3D_JOB, { id: row.id }, `asset3d-${row.id}-${Date.now()}`);
    }
    return this.forProduct(productId);
  }

  /** Worker: cut-out → gateway → validate budget → store public media → meter → READY. */
  async process(id: string) {
    const row = await this.prisma.garmentAsset3d.update({ where: { id }, data: { status: "GENERATING", progress: 15 } });
    try {
      const variant = await this.prisma.variant.findUnique({ where: { id: row.variantId }, include: { product: true } });
      if (!variant?.cutoutPath) throw new Error("Variant has no try-on cut-out");
      const cutout = await this.storage.read(variant.cutoutPath);
      const r = await this.ai.post<Garment3dResult>(
        "/v1/garment/3d",
        { cutout_b64: cutout.toString("base64"), category: variant.product.category, size: row.size, request_id: `asset3d-${id}` },
        120_000,
      );
      await this.prisma.garmentAsset3d.update({ where: { id }, data: { progress: 75 } });
      const glb = Buffer.from(r.glb_b64, "base64");
      const poster = Buffer.from(r.poster_b64, "base64");
      const problems = checkAssetBudget({ bytes: glb.length, triangles: r.triangles, posterBytes: poster.length, glbHead: glb.subarray(0, 12) });
      if (problems.length) throw new Error(`3D asset rejected: ${problems.join("; ")}`);
      const base = `public/media/${row.pageId}/${row.variantId}-3d`;
      const glbPath = await this.storage.put(`${base}.glb`, glb);
      const posterPath = await this.storage.put(`${base}-poster.webp`, poster);
      await this.prisma.mediaAsset.deleteMany({ where: { productId: row.productId, path: glbPath } });
      await this.prisma.mediaAsset.create({ data: { productId: row.productId, path: glbPath, kind: "MODEL_3D" } });
      await this.metering.record(ASSET_3D.kind, "PAGE_ALLOWANCE", ASSET_3D.costRwf, row.requestedBy, row.pageId, row.variantId);
      aiSpend.inc({ kind: ASSET_3D.kind }, ASSET_3D.costRwf);
      return await this.prisma.garmentAsset3d.update({
        where: { id },
        data: {
          status: "READY",
          progress: 100,
          glbPath,
          posterPath,
          bytes: glb.length,
          triangles: r.triangles,
          widthM: r.dimensions_m.width,
          heightM: r.dimensions_m.height,
          depthM: r.dimensions_m.depth,
          modelVersion: r.model_version,
          sha256: r.sha256,
          costRwf: ASSET_3D.costRwf,
          readyAt: new Date(),
        },
      });
    } catch (e) {
      this.log.warn(`3D asset ${id} failed: ${(e as Error).message}`);
      await this.prisma.garmentAsset3d.update({ where: { id }, data: { status: "FAILED", progress: 100, error: (e as Error).message.slice(0, 300) } });
      throw e;
    }
  }

  async approve(productId: string, approved: boolean) {
    const n = await this.prisma.garmentAsset3d.updateMany({ where: { productId, status: "READY" }, data: { approved } });
    if (approved && n.count === 0) throw new BadRequestException("No finished 3D model to approve yet");
    return this.forProduct(productId);
  }

  private view(a: GarmentAsset3d | undefined) {
    if (!a) return null;
    return {
      id: a.id,
      status: a.status,
      progress: a.progress,
      approved: a.approved,
      glb: this.storage.publicUrl(a.glbPath),
      poster: this.storage.publicUrl(a.posterPath),
      bytes: a.bytes,
      triangles: a.triangles,
      dimensions: a.heightM ? { width: a.widthM, height: a.heightM, depth: a.depthM } : null,
      size: a.size,
      modelVersion: a.modelVersion,
      error: a.error,
      updatedAt: a.updatedAt,
    };
  }

  /** Studio view: every colour with its 3D status (FR-3D-06 review). */
  async forProduct(productId: string) {
    const product = await this.prisma.product.findUniqueOrThrow({ where: { id: productId }, include: { variants: true } });
    const assets = await this.prisma.garmentAsset3d.findMany({ where: { productId } });
    const byVariant = new Map(assets.map((a) => [a.variantId, a]));
    const { cap, used } = await this.allowance(product.pageId);
    return {
      productId,
      label: AI_3D_LABEL,
      costRwf: ASSET_3D.costRwf,
      allowance: { cap, used },
      published: product.status === "PUBLISHED",
      variants: product.variants.map((v) => ({
        variantId: v.id,
        colourName: v.colourName,
        colourHex: v.colourHex,
        hasCutout: Boolean(v.cutoutPath),
        asset: this.view(byVariant.get(v.id)),
      })),
    };
  }

  /** Shopper view: only approved, finished models of a published product (FR-3D-06, FR-AR-05). */
  async publicForProduct(productId: string) {
    const product = await this.prisma.product.findUnique({ where: { id: productId }, include: { variants: true } });
    if (!product || product.status !== "PUBLISHED") return { productId, label: AI_3D_LABEL, assets: [] };
    const assets = await this.prisma.garmentAsset3d.findMany({ where: { productId, status: "READY", approved: true } });
    const byVariant = new Map(assets.map((a) => [a.variantId, a]));
    return {
      productId,
      title: product.title,
      label: AI_3D_LABEL,
      assets: product.variants
        .filter((v) => byVariant.has(v.id))
        .map((v) => {
          const a = byVariant.get(v.id)!;
          return {
            variantId: v.id,
            colourName: v.colourName,
            colourHex: v.colourHex,
            glb: this.storage.publicUrl(a.glbPath)!,
            poster: this.storage.publicUrl(a.posterPath),
            dimensions: { width: a.widthM ?? 0, height: a.heightM ?? 0, depth: a.depthM ?? 0 },
            triangles: a.triangles ?? 0,
            size: a.size,
          };
        }),
    };
  }
}
