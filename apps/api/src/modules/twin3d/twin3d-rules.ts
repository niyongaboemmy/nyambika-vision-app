/** Storage keys: private, per user, versioned. Fits live under their avatar so a purge removes them together. */
export const avatarBase = (userId: string, version: number) => `private/avatars/${userId}/v${version}`;
export const fitBase = (userId: string, version: number, variantId: string, size: string) => `${avatarBase(userId, version)}/fits/${variantId}-${size}`;
export function isAvatarPath(p: string) {
  return /^private\/avatars\/[a-z0-9]+\/v\d+\//i.test(p) && !p.includes("..");
}
