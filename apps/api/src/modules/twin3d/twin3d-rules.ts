/** Separate, explicit consent purpose for the 3D twin (FR-AVA-02); never implied by the photo twin consent. */
export const AVATAR_3D = "AVATAR_3D";

export const CAPTURE = { minFrames: 8, maxFrames: 32, maxFrameBytes: 400 * 1024, coverageBins: 12, minCoverage: 0.75 } as const;
export const AVATAR_COST = { kind: "AVATAR_3D", costRwf: 25, dailyCap: 6 } as const;
export const FIT_COST = { kind: "TRYON_3D", costRwf: 10 } as const;
export const AVATAR_LABEL = "3D twin generated by AI";
export const FIT_DISCLAIMER = "Visual guidance only. Actual fit may differ.";

export type AvatarSource = "TURNAROUND" | "PERSONA" | "MEASUREMENTS";
export type AvatarStatus = "QUEUED" | "BUILDING" | "READY" | "REJECTED" | "WITHHELD" | "FAILED";
export const BUILDING = new Set<AvatarStatus>(["QUEUED", "BUILDING"]);

/** Same 30° binning as the gateway (apps/ai/app/avatar_capture.coverage). */
export function coverageOf(yaws: number[]): number {
  const bins = new Set(yaws.map((y) => Math.floor((((y % 360) + 360) % 360) / (360 / CAPTURE.coverageBins))));
  return bins.size / CAPTURE.coverageBins;
}

export interface FrameIn {
  bytes: number;
  mime: string;
}

/** Cheap checks before anything is stored; the gateway runs the image checks (light, framing, rotation). */
export function validateCapture(frames: FrameIn[], yaws: number[]): string[] {
  const problems: string[] = [];
  if (frames.length < CAPTURE.minFrames) problems.push(`Need at least ${CAPTURE.minFrames} frames from the turn (got ${frames.length}).`);
  if (frames.length > CAPTURE.maxFrames) problems.push(`At most ${CAPTURE.maxFrames} frames.`);
  if (yaws.length !== frames.length) problems.push("Each frame needs its turn angle.");
  if (frames.some((f) => !/^image\/(jpeg|png|webp)$/.test(f.mime))) problems.push("Frames must be JPEG, PNG or WebP.");
  if (frames.some((f) => f.bytes > CAPTURE.maxFrameBytes)) problems.push("A frame is too large.");
  if (yaws.length === frames.length && frames.length && coverageOf(yaws) < CAPTURE.minCoverage) problems.push("Turn all the way round so we see every side.");
  return problems;
}

export function nextVersion(previous: { version: number } | null | undefined) {
  return (previous?.version ?? 0) + 1;
}

export type BuildGate = { ok: true } | { ok: false; code: "CONSENT_REQUIRED" | "DAILY_CAP" | "BUSY"; message: string };

export function canBuild(s: { consent: boolean; buildsToday: number; building: boolean; dailyCap?: number }): BuildGate {
  if (!s.consent) return { ok: false, code: "CONSENT_REQUIRED", message: "Turn on the 3D twin consent first." };
  if (s.building) return { ok: false, code: "BUSY", message: "Your 3D twin is still being built." };
  if (s.buildsToday >= (s.dailyCap ?? AVATAR_COST.dailyCap)) {
    return { ok: false, code: "DAILY_CAP", message: `You can build your 3D twin ${s.dailyCap ?? AVATAR_COST.dailyCap} times a day. Try again tomorrow.` };
  }
  return { ok: true };
}

/** Gateway job status → stored avatar status. */
export function mapJobStatus(s: string): AvatarStatus {
  switch (s) {
    case "DONE":
      return "READY";
    case "REJECTED":
      return "REJECTED";
    case "WITHHELD":
      return "WITHHELD";
    case "QUEUED":
    case "RUNNING":
      return "BUILDING";
    default:
      return "FAILED";
  }
}

/** Overall progress shown to the shopper: queue 0-10, gateway job 10-90, storing 90-100. */
export function progressFor(jobProgress: number) {
  return Math.min(90, 10 + Math.round(Math.max(0, Math.min(100, jobProgress)) * 0.8));
}

export const FULL = ["dress", "umushanana", "kitenge", "gown", "bridal", "wrap"];
export const TOPS = ["shirt", "top", "blouse", "jacket", "suit"];
export const BOTTOMS = ["skirt"];
export function supports3dTryOn(category: string | null | undefined) {
  const c = (category ?? "").toLowerCase();
  return FULL.includes(c) || TOPS.includes(c) || BOTTOMS.includes(c);
}

export const SIZE_ORDER = ["XS", "S", "M", "L", "XL", "XXL", "3XL"];

/** Sizes offered in the 3D viewer (the variant's chart) and the one to start with: the avatar's size, else the nearest. */
export function fitSizes(variantSizes: string[], bodySize: string | null | undefined) {
  const clean = [...new Set(variantSizes.map((s) => s.trim().toUpperCase()).filter((s) => SIZE_ORDER.includes(s)))].sort(
    (a, b) => SIZE_ORDER.indexOf(a) - SIZE_ORDER.indexOf(b),
  );
  const sizes = clean.length ? clean : ["S", "M", "L"];
  const target = SIZE_ORDER.indexOf((bodySize ?? "M").toUpperCase());
  const pick = sizes.reduce((best, s) => (Math.abs(SIZE_ORDER.indexOf(s) - target) < Math.abs(SIZE_ORDER.indexOf(best) - target) ? s : best), sizes[0]);
  return { sizes, recommended: pick };
}

