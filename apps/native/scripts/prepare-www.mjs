// Writes www/config.js (server URL for the offline page) and copies the app icon next to it.
// Run before `cap sync` (the `sync` script does this).
import { copyFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const url = (process.env.NYAMBIKA_SERVER_URL ?? "https://nyambika.rw").replace(/\/$/, "");
if (!/^https?:\/\/[^/]+$/.test(url)) throw new Error(`NYAMBIKA_SERVER_URL must be an origin, got ${url}`);
writeFileSync(resolve(root, "www/config.js"), `// Generated by scripts/prepare-www.mjs\nwindow.NYAMBIKA = ${JSON.stringify({ serverUrl: url })};\n`);
copyFileSync(resolve(root, "../../docs/nyambika_icon.png"), resolve(root, "www/icon.png"));
console.log(`www/config.js → ${url}`);
