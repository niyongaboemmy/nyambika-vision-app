"""Image-to-3D garment (E27, FR-3D-01a/02/03, FR-CAT-10).

From a try-on cut-out (RGBA, alpha = garment silhouette) build a lightweight GLB:
front and back panels sampled from the silhouette row by row, lifted into a body-like
volume (elliptical cross-section over the torso, thin over sleeves, gentle folds near the
hem), closed at the side seams, with the print as a PBR base-colour texture and alpha MASK
cutting the exact outline. Real-world metre scale comes from the category length and the
size (size chart), so AR "View in your space" shows true size (FR-AR-04).

No third-party 3D library: the glTF 2.0 binary container is written here (spec §4.4).
A provider adapter can later swap this for a learned image-to-3D model with the same output.
"""
from __future__ import annotations

import hashlib
import io
import json
import struct

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

MODEL_VERSION = "silhouette-lift@1.0"
AI_LABEL = "3D preview generated by AI"

# Garment length at size M in metres (shoulder/waist to hem), by category.
LENGTH_M = {
    "dress": 1.08, "umushanana": 1.32, "kitenge": 1.10, "gown": 1.35, "bridal": 1.40, "wrap": 1.05,
    "shirt": 0.74, "top": 0.62, "blouse": 0.64, "jacket": 0.76, "suit": 0.78,
    "skirt": 0.66, "kids": 0.62, "bag": 0.38, "shoes": 0.28,
}
SIZE_SCALE = {"XS": 0.94, "S": 0.97, "M": 1.0, "L": 1.03, "XL": 1.06, "XXL": 1.09, "3XL": 1.12}

ROWS = 72
COLS = 40
MAX_TEXTURE = 1024
MAX_GLB_BYTES = 2 * 1024 * 1024
MIN_THICK_M = 0.014


def garment_height_m(category: str | None, size: str | None) -> float:
    base = LENGTH_M.get((category or "dress").lower(), 1.0)
    return round(base * SIZE_SCALE.get((size or "M").upper(), 1.0), 3)


def _extents(alpha: np.ndarray, ys: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Left/right silhouette extent per sampled row (pixels), with gaps filled and edges smoothed."""
    h, w = alpha.shape
    left = np.full(len(ys), np.nan)
    right = np.full(len(ys), np.nan)
    for i, y in enumerate(ys):
        band = alpha[max(0, int(y) - 1): min(h, int(y) + 2)].max(axis=0)
        xs = np.nonzero(band > 127)[0]
        if len(xs) >= 2:
            left[i], right[i] = xs.min(), xs.max() + 1
    valid = ~np.isnan(left)
    if valid.sum() < 2:
        raise ValueError("Cut-out has no usable silhouette")
    idx = np.arange(len(ys))
    left = np.interp(idx, idx[valid], left[valid])
    right = np.interp(idx, idx[valid], right[valid])
    # Light smoothing so jagged alpha edges do not become a saw-tooth seam.
    k = np.array([0.25, 0.5, 0.25])
    left = np.convolve(np.pad(left, 1, mode="edge"), k, mode="valid")
    right = np.convolve(np.pad(right, 1, mode="edge"), k, mode="valid")
    return left, right, valid


def _mesh(alpha: np.ndarray, height_m: float, category: str):
    """Return positions, normals, uvs, colours (per vertex) and triangle indices."""
    h, w = alpha.shape
    ys = np.linspace(0, h - 1, ROWS)
    left, right, _ = _extents(alpha, ys)
    m_per_px = height_m / h
    cx = w / 2
    half = (right - left) / 2
    # Torso half-width: robust median of the row widths, sleeves excluded by the lower quantile.
    torso_half = float(np.quantile(half, 0.45))
    depth = min(0.12, torso_half * m_per_px * 0.72)  # half-depth of the body volume (m)
    cat = (category or "dress").lower()

    us = np.linspace(-1.0, 1.0, COLS)
    pos_f, pos_b, uv, col = [], [], [], []
    for r, y in enumerate(ys):
        x_px = left[r] + (us + 1) / 2 * (right[r] - left[r])
        x_m = (x_px - cx) * m_per_px
        t = np.abs(x_px - cx) / max(torso_half, 1.0)
        envelope = np.sqrt(np.clip(1 - us**2, 0, 1))
        body = depth * np.sqrt(np.clip(1 - t**2, 0, 1))
        z = envelope * (body + MIN_THICK_M)
        frac = r / (ROWS - 1)
        if frac > 0.55 and cat not in {"bag", "shoes"}:
            # Soft folds that grow towards the hem (fabric drape).
            z = z + envelope * 0.007 * ((frac - 0.55) / 0.45) * np.sin(us * np.pi * 7)
        y_m = (h - 1 - y) * m_per_px
        for side, store in ((1.0, pos_f), (-1.0, pos_b)):
            store.append(np.stack([x_m, np.full(COLS, y_m), side * z], axis=1))
        uv.append(np.stack([x_px / w, np.full(COLS, y / (h - 1))], axis=1))
        # Baked ambient occlusion: darker towards the side seams.
        col.append(np.repeat((0.78 + 0.22 * envelope)[:, None], 3, axis=1))

    pf = np.concatenate(pos_f)
    pb = np.concatenate(pos_b)
    uvs = np.concatenate(uv)
    cols = np.concatenate(col)
    positions = np.concatenate([pf, pb]).astype(np.float32)
    texcoords = np.concatenate([uvs, uvs]).astype(np.float32)
    colours = np.concatenate([cols, cols * 0.9]).astype(np.float32)

    n_side = ROWS * COLS
    tris = []
    for r in range(ROWS - 1):
        for c in range(COLS - 1):
            a = r * COLS + c
            b, d, e = a + 1, a + COLS, a + COLS + 1
            # Front panel faces +Z (counter-clockwise seen from the front); rows run top→bottom.
            tris.append((a, d, b))
            tris.append((b, d, e))
            # Back panel faces -Z: reverse winding.
            tris.append((n_side + a, n_side + b, n_side + d))
            tris.append((n_side + b, n_side + e, n_side + d))
    indices = np.asarray(tris, dtype=np.uint32)
    normals = _normals(positions, indices)
    return positions, normals, texcoords, colours, indices, {"depth_m": depth}


def _normals(positions: np.ndarray, indices: np.ndarray) -> np.ndarray:
    v0, v1, v2 = (positions[indices[:, i]] for i in range(3))
    face = np.cross(v1 - v0, v2 - v0)
    normals = np.zeros_like(positions)
    for i in range(3):
        np.add.at(normals, indices[:, i], face)
    length = np.linalg.norm(normals, axis=1, keepdims=True)
    length[length == 0] = 1
    return (normals / length).astype(np.float32)


def _texture(cut: Image.Image) -> bytes:
    """PNG with alpha (≤ 1024 px). Palette-quantised when large so the GLB stays well under budget."""
    tex = cut.copy()
    tex.thumbnail((MAX_TEXTURE, MAX_TEXTURE), Image.LANCZOS)
    buf = io.BytesIO()
    tex.save(buf, format="PNG", optimize=True)
    if buf.tell() > 900_000:
        buf = io.BytesIO()
        tex.quantize(256, method=Image.Quantize.FASTOCTREE).save(buf, format="PNG", optimize=True)
    return buf.getvalue()


def _pad(b: bytes, fill: bytes = b"\x00") -> bytes:
    return b + fill * ((4 - len(b) % 4) % 4)


def build_glb(positions, normals, texcoords, colours, indices, texture_png: bytes, extras: dict) -> bytes:
    blobs: list[bytes] = []
    views: list[dict] = []

    def add(data: bytes, target: int | None = None) -> int:
        offset = sum(len(b) for b in blobs)
        blobs.append(_pad(data))
        view = {"buffer": 0, "byteOffset": offset, "byteLength": len(data)}
        if target:
            view["target"] = target
        views.append(view)
        return len(views) - 1

    use16 = len(positions) < 65536
    idx = indices.astype(np.uint16 if use16 else np.uint32).reshape(-1)
    accessors = [
        {"bufferView": add(positions.tobytes(), 34962), "componentType": 5126, "count": len(positions), "type": "VEC3",
         "min": positions.min(axis=0).tolist(), "max": positions.max(axis=0).tolist()},
        {"bufferView": add(normals.tobytes(), 34962), "componentType": 5126, "count": len(normals), "type": "VEC3"},
        {"bufferView": add(texcoords.tobytes(), 34962), "componentType": 5126, "count": len(texcoords), "type": "VEC2"},
        {"bufferView": add(colours.tobytes(), 34962), "componentType": 5126, "count": len(colours), "type": "VEC3"},
        {"bufferView": add(idx.tobytes(), 34963), "componentType": 5123 if use16 else 5125, "count": len(idx), "type": "SCALAR"},
    ]
    image_view = add(texture_png)
    gltf = {
        "asset": {"version": "2.0", "generator": f"Nyambika AI Gateway {MODEL_VERSION}", "extras": extras},
        "extensionsUsed": ["KHR_materials_sheen"],
        "scene": 0,
        "scenes": [{"nodes": [0]}],
        "nodes": [{"mesh": 0, "name": "garment"}],
        "meshes": [{"name": "garment", "primitives": [{
            "attributes": {"POSITION": 0, "NORMAL": 1, "TEXCOORD_0": 2, "COLOR_0": 3},
            "indices": 4, "material": 0, "mode": 4}]}],
        "materials": [{
            "name": "fabric",
            "pbrMetallicRoughness": {"baseColorTexture": {"index": 0}, "metallicFactor": 0.0, "roughnessFactor": 0.86},
            "alphaMode": "MASK", "alphaCutoff": 0.5, "doubleSided": True,
            "extensions": {"KHR_materials_sheen": {"sheenColorFactor": [0.35, 0.33, 0.3], "sheenRoughnessFactor": 0.55}},
        }],
        "textures": [{"source": 0, "sampler": 0}],
        "images": [{"bufferView": image_view, "mimeType": "image/png"}],
        "samplers": [{"magFilter": 9729, "minFilter": 9987, "wrapS": 33071, "wrapT": 33071}],
        "accessors": accessors,
        "bufferViews": views,
        "buffers": [{"byteLength": sum(len(b) for b in blobs)}],
    }
    json_chunk = _pad(json.dumps(gltf, separators=(",", ":")).encode(), b" ")
    bin_chunk = b"".join(blobs)
    total = 12 + 8 + len(json_chunk) + 8 + len(bin_chunk)
    return b"".join([
        struct.pack("<III", 0x46546C67, 2, total),
        struct.pack("<II", len(json_chunk), 0x4E4F534A), json_chunk,
        struct.pack("<II", len(bin_chunk), 0x004E4942), bin_chunk,
    ])


def parse_glb(data: bytes) -> tuple[dict, bytes]:
    """Inverse of build_glb (used by tests and by the API-side validator)."""
    magic, version, length = struct.unpack_from("<III", data, 0)
    if magic != 0x46546C67 or version != 2 or length != len(data):
        raise ValueError("Not a glTF 2.0 binary")
    jlen, jtype = struct.unpack_from("<II", data, 12)
    if jtype != 0x4E4F534A:
        raise ValueError("First chunk must be JSON")
    gltf = json.loads(data[20:20 + jlen])
    off = 20 + jlen
    blen, btype = struct.unpack_from("<II", data, off)
    if btype != 0x004E4942:
        raise ValueError("Second chunk must be BIN")
    return gltf, data[off + 8: off + 8 + blen]


def _poster(cut: Image.Image, alpha: np.ndarray, size=(480, 600)) -> bytes:
    """Front view shaded with the same volume model (Lambert, key light upper-left) + floor shadow."""
    a = alpha.astype(np.float32) / 255
    h, w = a.shape
    ys = np.arange(h)
    left, right, _ = _extents(alpha, ys)
    xs = np.arange(w)[None, :]
    half = np.maximum((right - left) / 2, 1)[:, None]
    mid = ((left + right) / 2)[:, None]
    u = np.clip((xs - mid) / half, -0.999, 0.999)
    # Surface slope of z ≈ sqrt(1-u²): normal x-component = u / sqrt(1-u²) normalised.
    nz = np.sqrt(1 - u**2)
    nx = u
    light = np.array([-0.45, 0.35, 0.82])
    lam = np.clip(nx * light[0] + nz * light[2] + 0.35 * light[1], 0, 1)
    shade = 0.42 + 0.68 * lam
    rgb = np.asarray(cut.convert("RGB"), dtype=np.float32) * shade[..., None]
    lit = Image.fromarray(np.clip(rgb, 0, 255).astype(np.uint8)).convert("RGBA")
    lit.putalpha(Image.fromarray((a * 255).astype(np.uint8)))

    canvas = Image.new("RGBA", size, (0, 0, 0, 0))
    scale = min(size[0] * 0.78 / w, size[1] * 0.82 / h)
    gw, gh = max(1, int(w * scale)), max(1, int(h * scale))
    g = lit.resize((gw, gh), Image.LANCZOS)
    gx, gy = (size[0] - gw) // 2, int(size[1] * 0.05)
    shadow = Image.new("RGBA", size, (0, 0, 0, 0))
    ell = Image.new("L", (int(gw * 0.9), max(8, int(gh * 0.07))), 0)
    ImageDraw.Draw(ell).ellipse((0, 0, ell.width - 1, ell.height - 1), fill=150)
    shadow.paste((0, 0, 0, 255), (gx + (gw - ell.width) // 2, gy + gh - ell.height // 2), ell)
    canvas = Image.alpha_composite(canvas, shadow.filter(ImageFilter.GaussianBlur(10)))
    canvas.alpha_composite(g, (gx, gy))
    buf = io.BytesIO()
    canvas.save(buf, format="WEBP", quality=82, method=4)
    return buf.getvalue()


def generate(cutout: Image.Image, category: str | None = "dress", size: str | None = "M", request_id: str = "") -> dict:
    cut = cutout.convert("RGBA")
    alpha_full = np.asarray(cut)[..., 3]
    ys, xs = np.nonzero(alpha_full > 10)
    if len(ys) == 0:
        raise ValueError("Cut-out is empty")
    cut = cut.crop((int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1))
    # Work at ≤ 512 px for the mesh; the texture keeps up to MAX_TEXTURE.
    work = cut.copy()
    work.thumbnail((512, 512), Image.LANCZOS)
    alpha = np.asarray(work)[..., 3]
    height_m = garment_height_m(category, size)
    positions, normals, texcoords, colours, indices, info = _mesh(alpha, height_m, category or "dress")
    texture = _texture(cut)
    source_sha = hashlib.sha256(cut.tobytes()).hexdigest()
    extras = {
        "ai_generated": True,
        "label": AI_LABEL,
        "model_version": MODEL_VERSION,
        "request_id": request_id,
        "source_sha256": source_sha,
        "category": category,
        "size": size,
        "units": "metres",
    }
    glb = build_glb(positions, normals, texcoords, colours, indices, texture, extras)
    if len(glb) > MAX_GLB_BYTES:
        small = cut.copy()
        small.thumbnail((512, 512), Image.LANCZOS)
        glb = build_glb(positions, normals, texcoords, colours, indices, _texture(small), extras)
    lo, hi = positions.min(axis=0), positions.max(axis=0)
    dims = (hi - lo).tolist()
    return {
        "glb": glb,
        "poster": _poster(work, alpha),
        "triangles": int(len(indices)),
        "vertices": int(len(positions)),
        "bytes": len(glb),
        "dimensions_m": {"width": round(dims[0], 3), "height": round(dims[1], 3), "depth": round(dims[2], 3)},
        "model_version": MODEL_VERSION,
        "sha256": hashlib.sha256(glb).hexdigest(),
        "label": AI_LABEL,
    }
