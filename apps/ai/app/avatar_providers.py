"""3D avatar provider adapters (E33/E34, FR-AVA-01..06, FR-FIT-01).

Contract every provider implements (the API only ever sees this shape):

  build(frames, yaws, measurements, size_estimate, skin_rgb, style) ->
      {status: DONE | REJECTED | WITHHELD, glb, poster, triangles, vertices, joints, animations,
       skin_rgb, measurements_used, eval {skin_tone_delta, proportion_error, passed, ...},
       checks, model_version}
  dress(params, cutout, category, size) -> {glb, poster, fit {...}, triangles, model_version}

`parametric-cpu` (default, this repo) builds a stylised parametric body on CPU. A production
`gaussian-splat` provider would run 3D Gaussian splatting anchored on SMPL-X on GPUs (photoreal
style, FR-AVA-03) and must return the SAME contract: a skinned GLB proxy for <model-viewer> (SMPL-X
mesh + baked texture, same joint names) plus, optionally, a splat file for a splat renderer.
It is registered below as a slot that refuses to run until it is configured.
"""
from __future__ import annotations

import hashlib
import io
import os
from abc import ABC, abstractmethod
from typing import Callable

import numpy as np
from PIL import Image

from . import avatar_body as ab
from . import avatar_capture as cap
from . import avatar_dress as dress
from . import avatar_render as render
from . import c2pa, config

AI_LABEL = "3D twin generated by AI"
MAX_GLB_BYTES = 2 * 1024 * 1024
MAX_PROPORTION_ERROR = 0.03
DEFAULT_SKIN = (0.51, 0.36, 0.26)  # used only for measurement-only avatars without a chosen tone


def _poster(layers, request_id: str, model_version: str) -> bytes:
    """Server-side render (FR-AVA-04 fallback) on the studio background, as a C2PA-signed PNG."""
    webp = render.render(layers, size=(400, 600))
    img = Image.open(io.BytesIO(webp)).convert("RGBA")
    flat = Image.new("RGBA", img.size, (20, 17, 28, 255))
    flat.alpha_composite(img)
    png, _ = c2pa.sign(flat.convert("RGB"), model_version, request_id)
    return png


class AvatarProvider(ABC):
    name: str
    model_version: str

    @abstractmethod
    def build(self, frames: list[Image.Image], yaws: list[float], measurements: dict | None, size_estimate: str | None,
              skin_rgb: list[float] | None, style: str, request_id: str, progress: Callable[[int], None]) -> dict: ...

    @abstractmethod
    def dress(self, params: dict, cutout: Image.Image, category: str, size: str, request_id: str) -> dict: ...

    def info(self) -> dict:
        return {"id": self.model_version, "provider": self.name, "tier": "AVATAR", "kind": "avatar3d"}


class ParametricCpuProvider(AvatarProvider):
    name = "parametric-cpu"
    model_version = ab.MODEL_VERSION

    def build(self, frames, yaws, measurements, size_estimate, skin_rgb, style, request_id, progress):
        checks = None
        size = size_estimate
        sample = None
        if frames:
            progress(15)
            checks = cap.check_frames(frames, yaws)
            if not checks["ok"]:
                return {"status": "REJECTED", "checks": checks, "model_version": self.model_version}
            size = size or checks["estimated_size"]
            progress(35)
            sample = cap.sample_skin(frames, yaws)
            if not sample["rgb"]:
                return {"status": "REJECTED", "checks": {**checks, "ok": False, "checks": {**checks["checks"], "skin": {"pass": False, "note": "Face not visible in the front frames"}}},
                        "model_version": self.model_version}
            skin = sample["rgb"]
        else:
            skin = skin_rgb or list(DEFAULT_SKIN)
        progress(50)
        m, from_profile = ab.resolve_measurements(measurements, size)
        body = ab.build_body(m, skin)
        progress(70)
        extras = {"ai_generated": True, "label": AI_LABEL, "model_version": self.model_version, "request_id": request_id,
                  "style": "stylised", "likeness": False, "units": "metres"}
        glb, stats = ab.body_glb(body, extras)
        # Skin-tone guard (AI-GD-02 extended to avatars): the rendered material must match the sample.
        mat = ab.skin_material_rgba(body.skin_srgb)
        delta = float(np.abs(ab.skin_from_material(mat) - np.asarray(skin)).mean())
        perr = ab.proportion_error(body)
        ev = {
            "skin_tone_delta": round(delta, 5),
            "skin_sample_spread": sample["spread"] if sample else None,
            "proportion_error": round(perr, 5),
            "measured": {k: round(v, 1) for k, v in ab.measured(body).items()},
            "thresholds": {"skin_tone_delta": config.GUARD_MAX_SKIN_DELTA, "proportion_error": MAX_PROPORTION_ERROR},
        }
        ev["passed"] = delta <= config.GUARD_MAX_SKIN_DELTA and perr <= MAX_PROPORTION_ERROR and stats["triangles"] <= ab.MAX_TRIANGLES and len(glb) <= MAX_GLB_BYTES
        progress(85)
        poster = _poster(render.body_layers(body), request_id, self.model_version)
        status = "DONE" if ev["passed"] else "WITHHELD"
        return {
            "status": status, "glb": glb if status == "DONE" else None, "poster": poster if status == "DONE" else None,
            **stats, "bytes": len(glb), "skin_rgb": [round(float(c), 4) for c in body.skin_srgb],
            "skin_hex": "#" + "".join(f"{int(round(c * 255)):02X}" for c in body.skin_srgb),
            "measurements_used": m, "measurement_sources": from_profile, "size_estimate": size or ab.nearest_size(m),
            "body_size": ab.nearest_size(m), "eval": ev, "checks": checks, "model_version": self.model_version,
            "sha256": hashlib.sha256(glb).hexdigest(), "label": AI_LABEL,
        }

    def dress(self, params, cutout, category, size, request_id):
        m, _ = ab.resolve_measurements(params.get("measurements"), params.get("size_estimate"))
        skin = params.get("skin_rgb") or list(DEFAULT_SKIN)
        body = ab.build_body(m, skin)
        body_size = ab.nearest_size(m)
        garment = dress.fit(body, cutout, category, size, body_size)
        extras = {"ai_generated": True, "label": AI_LABEL, "model_version": f"{self.model_version}+{dress.MODEL_VERSION}",
                  "request_id": request_id, "category": category, "size": size, "fit": garment.info, "units": "metres"}
        glb, stats = ab.body_glb(body, extras, garment)
        if len(glb) > MAX_GLB_BYTES:
            raise ValueError("Dressed avatar over the 2 MB budget")
        fc, fa = garment.face_colours(dress.texture_image(garment))
        layers = render.body_layers(body) + [{"positions": garment.positions, "tris": garment.tris.astype(np.int64), "face_colours": fc, "alpha": fa, "two_sided": True}]
        poster = _poster(layers, request_id, extras["model_version"])
        return {"glb": glb, "poster": poster, "fit": garment.info, **stats, "bytes": len(glb),
                "model_version": extras["model_version"], "sha256": hashlib.sha256(glb).hexdigest(), "label": AI_LABEL}


class GaussianSplatProvider(AvatarProvider):
    """Adapter slot for a GPU 3DGS-on-SMPL-X service (e.g. a hosted avatar API).

    Configure AVATAR_3DGS_URL + AVATAR_3DGS_KEY. It must pass the NLB avatar extension
    (identity likeness, skin-tone fidelity, body-shape fidelity across subgroups; FR-AVA-05)
    before the host activates it in the model registry. Not implemented in this repository.
    """
    name = "gaussian-splat"
    model_version = "3dgs-smplx@unconfigured"

    def _refuse(self):
        raise NotImplementedError("gaussian-splat avatar provider is not configured (AVATAR_3DGS_URL)")

    def build(self, *a, **k):
        self._refuse()

    def dress(self, *a, **k):
        self._refuse()


PROVIDERS: dict[str, AvatarProvider] = {"parametric-cpu": ParametricCpuProvider(), "gaussian-splat": GaussianSplatProvider()}


def get(name: str | None = None) -> AvatarProvider:
    key = name or os.environ.get("AVATAR_PROVIDER", "parametric-cpu")
    if key not in PROVIDERS:
        raise ValueError(f"Unknown avatar provider '{key}'. Available: {sorted(PROVIDERS)}")
    return PROVIDERS[key]
