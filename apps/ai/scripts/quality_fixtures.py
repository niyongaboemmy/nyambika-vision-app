"""Try-on quality fixtures: the real product photo used by the lead's test, plus synthetic garments.

Real photo (LOCAL TESTS ONLY, never seeded, never committed):
  "BrownIEditShirt-plainBackground.png", Wikimedia Commons, CC BY-SA 3.0,
  https://commons.wikimedia.org/wiki/File:BrownIEditShirt-plainBackground.png
It carries a third-party word mark, so it is fetched at test time into `tests/fixtures/.cache/` (git-ignored)
and tests that need it skip when offline. Everything else here is generated by `make_seed_assets.py`.
"""
from __future__ import annotations

import io
import urllib.request
from pathlib import Path

from PIL import Image

import make_seed_assets as seeds

REAL_TEE_URL = "https://upload.wikimedia.org/wikipedia/commons/6/61/BrownIEditShirt-plainBackground.png"
REAL_TEE_CREDIT = "BrownIEditShirt-plainBackground.png, Wikimedia Commons, CC BY-SA 3.0 (local test only)"
CACHE = Path(__file__).resolve().parents[1] / "tests" / "fixtures" / ".cache"


def real_tee(cache_dir: Path = CACHE, side: int = 1000, timeout: float = 20.0) -> Image.Image | None:
    """The brown tee flattened on white (as a shop would upload it), or None when it cannot be fetched."""
    path = cache_dir / "brown-tee.png"
    if not path.exists():
        try:
            req = urllib.request.Request(REAL_TEE_URL, headers={"User-Agent": "NyambikaQualityTest/1.0"})
            raw = urllib.request.urlopen(req, timeout=timeout).read()  # noqa: S310 - fixed https URL
            img = Image.open(io.BytesIO(raw)).convert("RGBA")
        except Exception:  # noqa: BLE001 - offline: callers skip
            return None
        flat = Image.new("RGBA", img.size, (255, 255, 255, 255))
        flat.alpha_composite(img)
        flat = flat.convert("RGB")
        flat.thumbnail((side, side), Image.LANCZOS)
        cache_dir.mkdir(parents=True, exist_ok=True)
        flat.save(path)
    return Image.open(path).convert("RGB")


TEE_SHADES = {"dark": "#1F1F23", "brown": "#5C4033", "mid": "#C2553D", "light": "#C9D8E8"}


def synthetic(out: Path) -> dict[str, tuple[Path, str]]:
    """name -> (photo path, catalogue category) for the seeded-style garments used in the grid."""
    out.mkdir(parents=True, exist_ok=True)
    items = {
        "kitenge-dress": (seeds.garment("a-line-dress", "#C8553D", "circles", out / "kitenge-dress.png"), "dress"),
        "skirt": (seeds.garment("skirt", "#2F3E9E", "zigzag", out / "skirt.png"), "skirt"),
        "shirt": (seeds.garment("shirt", "#12857F", "waves", out / "shirt.png"), "shirt"),
    }
    for shade, hx in TEE_SHADES.items():
        items[f"tee-{shade}"] = (seeds.tee(hx, out / f"tee-{shade}.png"), "t-shirt")
    return items
