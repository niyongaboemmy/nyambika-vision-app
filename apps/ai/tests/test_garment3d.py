"""E27: image-to-3D garment GLB validity, bounds and budgets (FR-3D-02/03, FR-AR-04)."""
import base64
import io
import struct

import numpy as np
import pytest
from PIL import Image

from app import garment3d

from .conftest import b64

COMPONENTS = {"SCALAR": 1, "VEC2": 2, "VEC3": 3, "VEC4": 4}
BYTES = {5126: 4, 5125: 4, 5123: 2}
DTYPE = {5126: np.float32, 5125: np.uint32, 5123: np.uint16}


def _cutout(client, path) -> Image.Image:
    r = client.post("/v1/garment/assess", json={"image_b64": b64(path)}).json()
    return Image.open(io.BytesIO(base64.b64decode(r["cutout_b64"])))


def _accessor(gltf, binary, i):
    acc = gltf["accessors"][i]
    view = gltf["bufferViews"][acc["bufferView"]]
    n = acc["count"] * COMPONENTS[acc["type"]]
    assert view["byteLength"] == n * BYTES[acc["componentType"]]
    assert view["byteOffset"] % 4 == 0
    data = np.frombuffer(binary, dtype=DTYPE[acc["componentType"]], count=n, offset=view["byteOffset"])
    return data.reshape(acc["count"], -1) if COMPONENTS[acc["type"]] > 1 else data


@pytest.fixture(scope="module")
def dress(client, assets):
    return garment3d.generate(_cutout(client, assets / "dress-terracotta-circles.png"), "dress", "M", "t1")


def test_glb_container_is_valid_gltf2(dress):
    glb = dress["glb"]
    magic, version, length = struct.unpack_from("<III", glb, 0)
    assert (magic, version, length) == (0x46546C67, 2, len(glb))
    jlen = struct.unpack_from("<I", glb, 12)[0]
    assert jlen % 4 == 0 and len(glb) % 4 == 0
    gltf, binary = garment3d.parse_glb(glb)
    assert gltf["asset"]["version"] == "2.0"
    assert gltf["buffers"][0]["byteLength"] == len(binary)
    prim = gltf["meshes"][0]["primitives"][0]
    assert set(prim["attributes"]) == {"POSITION", "NORMAL", "TEXCOORD_0", "COLOR_0"}
    pos = _accessor(gltf, binary, prim["attributes"]["POSITION"])
    acc = gltf["accessors"][prim["attributes"]["POSITION"]]
    assert np.allclose(pos.min(axis=0), acc["min"]) and np.allclose(pos.max(axis=0), acc["max"])
    idx = _accessor(gltf, binary, prim["indices"])
    assert idx.max() < len(pos) and len(idx) % 3 == 0
    nrm = _accessor(gltf, binary, prim["attributes"]["NORMAL"])
    assert np.allclose(np.linalg.norm(nrm, axis=1), 1, atol=1e-3)
    uv = _accessor(gltf, binary, prim["attributes"]["TEXCOORD_0"])
    assert uv.min() >= 0 and uv.max() <= 1
    # Every accessor count matches the vertex count.
    for name in ("NORMAL", "TEXCOORD_0", "COLOR_0"):
        assert gltf["accessors"][prim["attributes"][name]]["count"] == len(pos)


def test_pbr_material_texture_and_ai_label(dress):
    gltf, binary = garment3d.parse_glb(dress["glb"])
    mat = gltf["materials"][0]
    pbr = mat["pbrMetallicRoughness"]
    assert pbr["metallicFactor"] == 0 and 0.5 < pbr["roughnessFactor"] <= 1
    assert mat["alphaMode"] == "MASK" and mat["doubleSided"] is True
    img = gltf["images"][pbr["baseColorTexture"]["index"]]
    view = gltf["bufferViews"][img["bufferView"]]
    tex = Image.open(io.BytesIO(binary[view["byteOffset"]: view["byteOffset"] + view["byteLength"]]))
    assert img["mimeType"] == "image/png" and max(tex.size) <= 2048
    assert "A" in tex.convert("RGBA").getbands()
    assert gltf["asset"]["extras"]["ai_generated"] is True
    assert gltf["asset"]["extras"]["label"] == "3D preview generated by AI"


def test_budgets(dress):
    assert dress["bytes"] <= 2 * 1024 * 1024
    assert dress["triangles"] <= 50_000
    assert len(dress["poster"]) <= 300 * 1024
    poster = Image.open(io.BytesIO(dress["poster"]))
    assert poster.format == "WEBP" and poster.mode == "RGBA"


def test_metre_scale_bounds_and_volume(dress):
    d = dress["dimensions_m"]
    assert abs(d["height"] - garment3d.garment_height_m("dress", "M")) < 0.02
    assert 0.25 < d["width"] < 1.4
    assert 0.03 < d["depth"] < 0.4  # a body-like volume, not a flat card
    gltf, binary = garment3d.parse_glb(dress["glb"])
    prim = gltf["meshes"][0]["primitives"][0]
    pos = _accessor(gltf, binary, prim["attributes"]["POSITION"])
    nrm = _accessor(gltf, binary, prim["attributes"]["NORMAL"])
    assert pos[:, 1].min() >= 0  # stands on the floor for AR placement
    front = pos[:, 2] > 0.02
    assert (nrm[front, 2] > 0).mean() > 0.9  # outward-facing front panel
    assert (nrm[pos[:, 2] < -0.02, 2] < 0).mean() > 0.9


def test_size_chart_scales_model(client, assets):
    cut = _cutout(client, assets / "shirt-teal-waves.png")
    s = garment3d.generate(cut, "shirt", "S")["dimensions_m"]["height"]
    xl = garment3d.generate(cut, "shirt", "XL")["dimensions_m"]["height"]
    assert xl > s
    assert 0.6 < s < 0.85


def test_endpoint_and_empty_cutout(client, assets):
    r = client.post("/v1/garment/3d", json={"cutout_b64": b64(assets / "skirt-terracotta-circles.png"),
                                            "category": "skirt", "size": "L"})
    assert r.status_code == 200
    body = r.json()
    glb = base64.b64decode(body["glb_b64"])
    assert glb[:4] == b"glTF" and body["bytes"] == len(glb) and body["triangles"] <= 50_000
    assert body["label"] == "3D preview generated by AI"
    empty = Image.new("RGBA", (64, 64), (0, 0, 0, 0))
    buf = io.BytesIO()
    empty.save(buf, format="PNG")
    r = client.post("/v1/garment/3d", json={"cutout_b64": base64.b64encode(buf.getvalue()).decode()})
    assert r.status_code == 422
